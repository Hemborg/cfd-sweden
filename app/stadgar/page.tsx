import { PageLayout } from "@/components/PageLayout";

export default function StadgarPage() {
  return (
    <PageLayout
      current="bylaws"
      eyebrow="Stadgar"
      title="Stadgar för Citizens for Disclosure Sweden"
      intro="Dessa stadgar är ett utkast inför föreningens planerade bildande 2027-01-14"
    >
      <section className="subpage-section">
        <article className="large-copy bylaws">

          <h2>Allmänna bestämmelser</h2>

          <h3>1 § Ändamål</h3>
          <p>Föreningens namn är Citizens for Disclosure Sweden.</p>
          <p>Föreningen ska verka för transparens, kunskapande och informationsspridning kring existensen av utomjordisk närvaro och verksamhet på jorden.</p>
          <p>Föreningen vänder sig till alla oavsett ålder och bakgrund, och ska aktivt motverka diskriminering.</p>

          <h3>2 § Säte</h3>
          <p>Föreningen har sitt säte i Stockholms kommun.</p>

          <h3>3 § Beslutande organ</h3>
          <p>Föreningens beslutande organ är årsmöte, extra årsmöte och styrelsen.</p>

          <h3>4 § Firmateckning</h3>
          <p>Föreningens firma tecknas av styrelsen gemensamt eller, om styrelsen så beslutar, av två styrelseledamöter gemensamt eller var för sig.</p>

          <h3>5 § Verksamhets- och räkenskapsår</h3>
          <p>Föreningens verksamhets- och räkenskapsår är kalenderår. Det första verksamhetsåret omfattar tiden från bildandet till och med den 31 december 2027.</p>

          <h3>6 § Stadgetolkning</h3>
          <p>Uppstår tvekan om tolkningen av dessa stadgar hänskjuts frågan till nästkommande årsmöte. I brådskande fall får styrelsen avgöra.</p>

          <h3>7 § Tvist</h3>
          <p>Tvist mellan medlem och föreningen avgörs av allmän domstol.</p>

          <h3>8 § Stadgeändring</h3>
          <p>Ändring av dessa stadgar kräver beslut på två på varandra följande möten, med minst en månads mellanrum, varav ett ska vara årsmöte, med minst 2/3 av antalet avgivna röster.</p>

          <h3>9 § Upplösning</h3>
          <p>Upplösning av föreningen kräver beslut på två på varandra följande möten, med minst en månads mellanrum, varav ett ska vara årsmöte, med minst 2/3 av antalet avgivna röster. Vid upplösning skänks föreningens tillgångar till Allmänna Arvsfonden.</p>

          <h2>Medlemmar</h2>

          <h3>10 § Medlemskap</h3>
          <p>Föreningen är öppen för alla fysiska personer. Medlem ska följa stadgarna. Medlemskapet börjar när medlemsavgiften är betald och gäller tills vidare. Styrelsen kan utse hedersmedlemmar.</p>
          <p>Genom sitt medlemskap godkänner medlem att föreningen behandlar personuppgifter i enlighet med GDPR.</p>

          <h3>11 § Uträde</h3>
          <p>Medlem som vill uträda anmäler detta skriftligen till styrelsen. Medlem som inte betalat medlemsavgift senast 31 december anses ha uträtt.</p>

          <h3>12 § Uteslutning</h3>
          <p>Medlem får uteslutas om denne försummat att betala beslutade avgifter, motarbetat föreningens ändamål, eller uppenbart skadat föreningens intressen. Medlemmen ska ges minst 14 dagar att yttra sig innan beslut fattas. Beslutet ska motiveras skriftligen och meddelas inom tre dagar.</p>

          <h3>13 § Medlems rättigheter och skyldigheter</h3>
          <p>Medlem har rätt att delta i föreningens sammankomster och ta del av information om föreningens angelägenheter. Medlem ska följa stadgarna, betala beslutade avgifter, och har inte rätt till del av föreningens tillgångar vid upplösning.</p>

          <h2>Årsmöte</h2>

          <h3>14 § Tidpunkt och kallelse</h3>
          <p>Årsmötet hålls före utgången av mars. Kallelse med dagordning ska tillställas medlemmarna senast tre veckor före mötet via e-post och föreningens hemsida. Handlingar ska finnas tillgängliga på föreningens hemsida senast en vecka före mötet.</p>

          <h3>15 § Motioner</h3>
          <p>Medlem och styrelse får avge förslag till årsmötet. Motioner ska vara styrelsen tillhanda senast fyra veckor före mötet.</p>

          <h3>16 § Rösträtt</h3>
          <p>Medlem som betalt avgiften senast 30 dagar före mötet och under mötesåret fyller minst 15 år har rösträtt. Rösträtten är personlig och kan inte utövas genom ombud.</p>

          <h3>17 § Beslut</h3>
          <p>Mötet är beslutsmässigt med de röstberättigade som är närvarande. Beslut fattas med enkel majoritet. Val avgörs med relativ majoritet. Vid lika röstetal i sakfrågor har mötesordföranden utslagsröst; vid val avgör lotten.</p>

          <h3>18 § Ärenden vid årsmötet</h3>
          <p>Vid årsmötet ska följande behandlas:</p>
          <ol>
            <li>Fastställande av röstlängd</li>
            <li>Val av mötesordförande, sekreterare, protokolljusterare och rösträknare</li>
            <li>Fråga om stadgeenlig kallelse</li>
            <li>Fastställande av dagordning</li>
            <li>Verksamhets- och förvaltningsberättelse</li>
            <li>Revisionsberättelse</li>
            <li>Fråga om ansvarsfrihet för styrelsen</li>
            <li>Fastställande av medlemsavgifter</li>
            <li>Verksamhetsplan och budget</li>
            <li>Propositioner och motioner</li>
            <li>Val av ordförande (1 år), övriga styrelseledamöter (2 år), revisor (1 år) och valberedning (1 år)</li>
            <li>Övriga i kallelsen angivna ärenden</li>
          </ol>

          <h3>19 § Extra årsmöte</h3>
          <p>Styrelsen kan kalla till extra årsmöte och är skyldig att göra det om revisorn eller minst 10 % av de röstberättigade medlemmarna skriftligen begär det. Kallelse ska ske senast sju dagar före mötet. Endast det som föranlett mötet får behandlas.</p>

          <h2>Valberedning och revision</h2>

          <h3>20 § Valberedning</h3>
          <p>Valberedningen består av minst en ledamot vald av årsmötet. Valberedningen ska meddela sitt förslag till röstberättigade medlemmar senast två veckor före årsmötet.</p>

          <h3>21 § Revision</h3>
          <p>Föreningens räkenskaper och förvaltning granskas av en revisor utsedd av årsmötet. Revisorn ska vara oberoende av styrelsen. Revisionsberättelse ska överlämnas senast 14 dagar före årsmötet.</p>

          <h2>Styrelsen</h2>

          <h3>22 § Sammansättning</h3>
          <p>Styrelsen består av ordförande samt minst två övriga ledamöter. Styrelsen utser inom sig vice ordförande, sekreterare och kassör.</p>

          <h3>23 § Åligganden</h3>
          <p>Styrelsen ansvarar för föreningens angelägenheter mellan årsmötena, verkställer årsmötets beslut, förvaltar föreningens medel och förbereder årsmöte.</p>

          <h3>24 § Sammanträden</h3>
          <p>Styrelsen sammanträder på kallelse av ordföranden eller om minst halva antalet ledamöter begär det. Styrelsen är beslutsmässig när samtliga kallats och minst hälften är närvarande. Vid lika röstetal har ordföranden utslagsröst. Protokoll ska föras och justeras.</p>

          <p className="bylaws-footer">Stadgarna planeras att antas vid konstituerande möte 2027-01-14.</p>

        </article>
      </section>
    </PageLayout>
  );
}
